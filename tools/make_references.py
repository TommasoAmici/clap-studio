#!/usr/bin/env python3
"""Regenerate Tests/ClapCoreTests/References.swift: ground truth from librosa / Hugging Face that the
Swift front ends, tokenizer and Core ML models are checked against.

    tools/.venv/bin/python tools/make_references.py
"""
import os
import warnings

import librosa
import numpy as np
import torch

warnings.filterwarnings("ignore")
OUT = os.path.join(os.path.dirname(__file__), "..", "Tests", "ClapCoreTests", "References.swift")
NAME = "laion/clap-htsat-unfused"
PHRASES = ["a punchy kick drum", "closed hi hat", "808 bass with long tail", "Warm analog pad, slow attack!",
           "snare  with   reverb", "it's a vinyl crackle", "ÉTÉ café 909"]


def signal(rate, seconds=0.5):
    t = np.arange(int(rate * seconds)) / rate
    s = 0.5 * np.sin(2 * np.pi * 220 * t) * np.exp(-6 * t) + 0.2 * np.sin(2 * np.pi * 3000 * t) * np.exp(-20 * t)
    return s.astype(np.float32)


def fmt(values):
    return "[" + ", ".join(f"{float(v):.6g}" for v in np.asarray(values).ravel()) + "]"


def panns_mel(x):
    stft = librosa.stft(x.astype(np.float64), n_fft=1024, hop_length=320, window="hann", center=True, pad_mode="reflect")
    fb = librosa.filters.mel(sr=32000, n_fft=1024, n_mels=64, fmin=50, fmax=14000)
    return 10 * np.log10(np.maximum(fb @ (np.abs(stft) ** 2), 1e-10)).T      # (frames, 64)


def main():
    from transformers import ClapModel, ClapProcessor

    model = ClapModel.from_pretrained(NAME).eval()
    proc = ClapProcessor.from_pretrained(NAME)
    lines = ["// Generated by tools/make_references.py. Do not edit.", "", "enum Reference {"]

    pm = panns_mel(signal(32000))
    rows = [0, 1, 20, 48]
    lines.append(f"    static let pannsRows = {rows}")
    lines.append(f"    static let pannsMel: [[Float]] = [{', '.join(fmt(pm[r]) for r in rows)}]")

    fe = proc.feature_extractor(signal(48000), sampling_rate=48000, truncation="rand_trunc", padding="repeatpad",
                                return_tensors="pt")
    feats = fe["input_features"]                                # (1, 1, 1001, 64)
    rows = [0, 1, 2, 250, 500, 999, 1000]
    lines.append(f"    static let clapRows = {rows}")
    lines.append(f"    static let clapMel: [[Float]] = [{', '.join(fmt(feats[0, 0, r]) for r in rows)}]")
    with torch.no_grad():
        emb = model.get_audio_features(input_features=feats, is_longer=torch.zeros(1, 1, dtype=torch.bool))
    lines.append(f"    static let clapEmbedding: [Float] = {fmt(emb[0].numpy())}")

    lines.append("    static let phrases: [String] = [" + ", ".join('"%s"' % p for p in PHRASES) + "]")
    ids, vecs = [], []
    for p in PHRASES:
        e = proc.tokenizer([p], padding="max_length", max_length=48, return_tensors="pt")
        ids.append([int(i) for i in e["input_ids"][0]])
        with torch.no_grad():
            vecs.append(model.get_text_features(input_ids=e["input_ids"], attention_mask=e["attention_mask"])[0].numpy())
    lines.append("    static let tokenIDs: [[Int32]] = [" + ", ".join(str(i) for i in ids) + "]")
    lines.append("    static let textEmbeddings: [[Float]] = [" + ", ".join(fmt(v) for v in vecs) + "]")
    lines.append("}")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.abspath(OUT))


if __name__ == "__main__":
    main()
